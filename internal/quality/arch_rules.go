package quality

import (
	"fmt"
	"os"
	"path/filepath"
)

type ArchRuleConfig struct {
	EnforceThinControllers   bool `json:"enforceThinControllers"`
	EnforceSinglePurposeActions bool `json:"enforceSinglePurposeActions"`
	EnforcePureModels        bool `json:"enforcePureModels"`
	EnforceStrictTypes       bool `json:"enforceStrictTypes"`
}

// GeneratePestArchitectureSuite generates a Pest PHP architecture test file matching Best Practices Doctor rules
func GeneratePestArchitectureSuite(cfg ArchRuleConfig) string {
	content := `<?php

declare(strict_types=1);

/**
 * Architectural Governance Suite
 * Generated by LaraDeck — Best Practices Doctor
 */

// 1. General code style & safety
arch('strict types are declared')
    ->expect('App')
    ->toUseStrictTypes();

arch('no debugging statements remain')
    ->expect(['dd', 'dump', 'ray', 'var_dump'])
    ->not->toBeUsed();
`

	if cfg.EnforceThinControllers {
		content += `
// 2. Controller layer governance
arch('controllers are thin and delegate to actions or services')
    ->expect('App\Http\Controllers')
    ->not->toUse('Illuminate\Database\Eloquent\Model');
`
	}

	if cfg.EnforceSinglePurposeActions {
		content += `
// 3. Action layer governance
arch('actions are single purpose and contain a handle method')
    ->expect('App\Actions')
    ->toHaveMethod('handle');
`
	}

	if cfg.EnforcePureModels {
		content += `
// 4. Domain & Model governance
arch('models do not handle HTTP concerns')
    ->expect('App\Models')
    ->not->toUse(['Illuminate\Http\Request', 'Inertia\Inertia', 'Inertia\Response']);
`
	}

	return content
}

// WritePestArchitectureFile writes the architecture test into tests/Feature/ArchitectureTest.php if it doesn't overwrite without confirmation
func WritePestArchitectureFile(projectPath string, cfg ArchRuleConfig, overwrite bool) (string, error) {
	targetDir := filepath.Join(projectPath, "tests", "Feature")
	if err := os.MkdirAll(targetDir, 0755); err != nil {
		return "", err
	}
	targetPath := filepath.Join(targetDir, "ArchitectureTest.php")
	if !overwrite {
		if _, err := os.Stat(targetPath); err == nil {
			return "", fmt.Errorf("ArchitectureTest.php already exists at %s; enable overwrite to replace", targetPath)
		}
	}

	suite := GeneratePestArchitectureSuite(cfg)
	if err := os.WriteFile(targetPath, []byte(suite), 0644); err != nil {
		return "", err
	}
	return targetPath, nil
}
